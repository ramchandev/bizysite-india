import fs from "node:fs";
import path from "node:path";

const APP_DIR = path.join(process.cwd(), "src/app");
const OUT_FILE = path.join(process.cwd(), "src/data/generatedSearchBodies.ts");

/** Convert a page file path under src/app to a site href. */
function fileToHref(filePath) {
  const rel = path.relative(APP_DIR, filePath).replace(/\\/g, "/");
  if (!rel.endsWith("/page.tsx") && !rel.endsWith("/page.ts")) return null;
  if (rel.includes("[")) return null; // dynamic routes handled elsewhere

  const dir = path.posix.dirname(rel);
  if (dir === ".") return "/";
  return `/${dir}`;
}

/**
 * Pull human-readable strings out of a TSX/TS source file.
 * Favor string literals (bios, copy, metadata) over JSX plumbing.
 */
function extractText(source) {
  const cleaned = source
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/^\s*import\s.+?;?\s*$/gm, " ")
    .replace(/^\s*export\s+type\s.+$/gm, " ");

  const chunks = [];
  const stringRe = /(["'`])((?:\\.|(?!\1)[\s\S])*?)\1/g;
  let match;
  while ((match = stringRe.exec(cleaned)) !== null) {
    const raw = match[2]
      .replace(/\\n/g, " ")
      .replace(/\\'/g, "'")
      .replace(/\\"/g, '"')
      .replace(/\\`/g, "`")
      .replace(/\s+/g, " ")
      .trim();

    if (raw.length < 12) continue;
    // Skip paths, class-like tokens, and pure CSS/color noise
    if (/^\/[a-z0-9\-/_[\].]+$/i.test(raw)) continue;
    if (/^(var\(--|rgba?\(|#[0-9a-f]{3,8})/i.test(raw)) continue;
    if (/^(flex|grid|none|block|inline|absolute|relative|sticky)/i.test(raw) && raw.length < 40) {
      continue;
    }
    chunks.push(raw);
  }

  return chunks.join(" ").replace(/\s+/g, " ").trim();
}

function walkPages(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "api") continue;
      walkPages(full, files);
    } else if (entry.name === "page.tsx" || entry.name === "page.ts") {
      files.push(full);
    }
  }
  return files;
}

const bodies = {};
for (const file of walkPages(APP_DIR)) {
  const href = fileToHref(file);
  if (!href) continue;
  const text = extractText(fs.readFileSync(file, "utf8"));
  if (text.length > 40) {
    bodies[href] = text.slice(0, 20000);
  }
}

// Dynamic work case-study page: share extracted copy across each slug
const workSlugPage = path.join(APP_DIR, "work/[slug]/page.tsx");
if (fs.existsSync(workSlugPage)) {
  const workText = extractText(fs.readFileSync(workSlugPage, "utf8"));
  const slugRe = /"([a-z0-9-]+)"\s*:\s*\{/g;
  const source = fs.readFileSync(workSlugPage, "utf8");
  let slugMatch;
  while ((slugMatch = slugRe.exec(source)) !== null) {
    const slug = slugMatch[1];
    if (["dr-sajan-hegde", "sound-v-pro", "miracle-members", "an-art-by", "idea-heavens"].includes(slug)) {
      bodies[`/work/${slug}`] = workText.slice(0, 20000);
    }
  }
}
const header = `/**
 * AUTO-GENERATED by scripts/extract-search-bodies.mjs
 * Do not edit by hand. Re-run: node scripts/extract-search-bodies.mjs
 */
export const generatedSearchBodies: Record<string, string> = ${JSON.stringify(
  bodies,
  null,
  2
)};
`;

fs.writeFileSync(OUT_FILE, header, "utf8");
console.log(
  `Wrote ${Object.keys(bodies).length} page bodies to ${path.relative(process.cwd(), OUT_FILE)}`
);
